async function review(providers) {
  const report = JSON.parse(readFileSync(resolve(OUT, "report.json"), "utf8"));
  const summary = [];
  for (const cand of report) {
    // full-frame states for composition (3) + every labeled close-up for component detail
    const shots = cand.screenshots.filter(existsSync).slice(0, 3);
    const closeups = (cand.closeups || []).filter(existsSync);
    if (!shots.length && !closeups.length) continue;
    console.log(`\n── vision review: ${cand.title} (${shots.length} fulls + ${closeups.length} close-ups × ${providers.length} models) ──`);
    const content = [
      { type: "text", text: `${BRIEF}\n\nCANDIDATE SPEC: ${cand.title} [${cand.target}]` },
      ...shots.flatMap((p) => [
        { type: "text", text: `FULL FRAME · STATE: ${basename(p).replace(/^\d+-|\.png$/g, "")}` },
        img(readFileSync(p).toString("base64")),
      ]),
      ...closeups.flatMap((p) => {
        const key = basename(p).replace(/^cu-|\.png$/g, "");
        return [
          { type: "text", text: CU_LABELS[key] || `CLOSE-UP 3× — ${key}` },
          img(readFileSync(p).toString("base64")),
        ];
      }),
    ];
    for (const p of providers) {
      process.stdout.write(`  ${p} … `);
      try {
        const j = await chat(p, content);
        const raw = j.content || j.choices?.[0]?.message?.content || "";
        const parsed = parseJson(raw);
        const out = { provider: p, model: j.model, costUsd: j.costUsd, ...parsed };
        writeFileSync(resolve(OUT, cand.seed, `findings-${p}.json`), JSON.stringify(out, null, 2));
        summary.push({ candidate: cand.seed, provider: p, findings: (parsed.findings || []).length, ideas: (parsed.ideas || []).length });
        console.log(`${(parsed.findings || []).length} findings · ${(parsed.ideas || []).length} ideas`);
      } catch (e) {
        summary.push({ candidate: cand.seed, provider: p, error: String(e.message).slice(0, 120) });
        console.log(`FAIL — ${String(e.message).slice(0, 80)}`);
      }
    }
  }
  writeFileSync(resolve(OUT, "findings-summary.json"), JSON.stringify(summary, null, 2));
  console.log("\nwrote .verify/findings-summary.json");
}

async function main() {
  const all = argProviders
    ? argProviders.split(",")
    : (await (await fetch(`${BASE}/api/arena/providers`)).json()).providers.map((p) => p.id);
  console.log("capability probe:");
  const visionOk = await probe(all);
  console.log(`vision-capable: [${visionOk.join(", ")}]`);
  if (PROBE_ONLY || !visionOk.length) return;
  await review(visionOk);
}
main().catch((e) => { console.error(e); process.exit(2); });
