import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { basename, dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const arenaDir = resolve(here, "../..");
const OUT = resolve(arenaDir, ".verify");
const BASE = "http://localhost:5273";

// 16x16 solid #e02020 — generated by Playwright (1x1 probes are ambiguous after model-side
// rescaling, and xai rejects images under 8px)
const RED_PX = readFileSync(resolve(OUT, "probe-red.png")).toString("base64");

const argProviders = (process.argv.find((a) => a.startsWith("--providers=")) || "").split("=")[1];
const PROBE_ONLY = process.argv.includes("--probe");

async function chat(provider, content) {
  const r = await fetch(`${BASE}/api/arena/chat`, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({ provider, messages: [{ role: "user", content }] }),
  });
  const j = await r.json().catch(() => ({}));
  if (!r.ok) throw new Error(j.error || `HTTP ${r.status}`);
  return j;
}

function img(b64) {
  return { type: "image_url", image_url: { url: `data:image/png;base64,${b64}` } };
}
function parseJson(text) {
  let t = String(text || "").trim();
  if (t.startsWith("```")) t = t.replace(/^```[a-zA-Z]*\s*\n?/, "").replace(/\n?```\s*$/, "");
  const start = t.indexOf("{");
  if (start > 0) t = t.slice(start);
  return JSON.parse(t);
}

async function probe(providers) {
  const ok = [];
  for (const p of providers) {
    process.stdout.write(`  probe ${p} … `);
    try {
      const j = await chat(p, [
        { type: "text", text: 'One word: what color is this image? Reply as JSON {"color":"..."}' },
        img(RED_PX),
      ]);
      const txt = (j.content || j.choices?.[0]?.message?.content || JSON.stringify(j)).toLowerCase();
      const sees = txt.includes("red");
      console.log(sees ? "VISION OK" : `no ("${txt.slice(0, 60)}")`);
      if (sees) ok.push(p);
    } catch (e) {
      console.log(`FAIL — ${String(e.message).slice(0, 80)}`);
    }
  }
  return ok;
}

